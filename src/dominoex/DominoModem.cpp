struct Spec {
  const char* name;
  double baud;
  int doubled;
};

const Spec kModes[] = {
    {"DominoEX Micro", 2.0, 1},
    {"DominoEX 4", 8000.0 / 2048.0, 2},
    {"DominoEX 5", 11025.0 / 2048.0, 2},
    {"DominoEX 8", 8000.0 / 1024.0, 2},
    {"DominoEX 11", 11025.0 / 1024.0, 1},
    {"DominoEX 16", 8000.0 / 512.0, 1},
    {"DominoEX 22", 11025.0 / 512.0, 1},
};

const Spec* specFor(const QString& mode) {
  for (const Spec& spec : kModes) {
    if (mode == QLatin1String(spec.name))
      return &spec;
  }
  return nullptr;
}

double spacingHz(const Spec& spec) {
  return spec.baud * double(spec.doubled);
}

